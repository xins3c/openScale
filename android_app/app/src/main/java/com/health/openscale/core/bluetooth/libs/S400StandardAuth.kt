package com.health.openscale.core.bluetooth.libs

import org.bouncycastle.crypto.engines.AESEngine
import org.bouncycastle.crypto.modes.CCMBlockCipher
import org.bouncycastle.crypto.params.AEADParameters
import org.bouncycastle.crypto.params.KeyParameter
import java.nio.ByteBuffer
import java.nio.ByteOrder
import javax.crypto.Mac
import javax.crypto.spec.SecretKeySpec

/**
 * StandardAuth key agreement, confirmation and AES-CCM transport for the
 * Xiaomi Body Composition Scale S400 (FE95 GATT service).
 *
 * This is a pure Kotlin/JVM component: it holds no keys, touches no Android or
 * Bluetooth APIs, and every function is deterministic — the caller supplies the
 * device token, the per-session randoms and the frame counters and receives the
 * derived material. Secret inputs and outputs are never logged or stored here.
 *
 * Protocol (reconstructed from the vendor JADX sources and independently
 * re-validated against captured traffic; see docs/notes in the repository):
 *
 *   session key  SK = HKDF-SHA256(IKM = token, salt = appRandom || devRandom,
 *                                 info = "mible-login-info", L = 64)
 *                   vendor: BleStandardAuthLoginConnector.deriveSessionKey
 *   SK layout    SK[ 0:16] device-confirmation key == RX (device->app) key
 *                SK[16:32] app-confirmation key    == TX (app->device) key
 *                SK[32:36] RX nonce prefix
 *                SK[36:40] TX nonce prefix
 *
 *   confirmations  deviceConfirm = HMAC-SHA256(SK[ 0:16], devRandom || appRandom)
 *                  appConfirm    = HMAC-SHA256(SK[16:32], appRandom || devRandom)
 *                  vendor: BleStandardAuthLoginConnector recvDevConfirmation /
 *                          recvDevRandom (u3p.sha256HMAC)
 *
 *   AES-CCM frames (4-byte tag, no associated data):
 *                  nonce   = prefix[4] || 00 00 00 00 || counter[4] (little-endian)
 *                  TX: key = SK[16:32], prefix = SK[36:40],
 *                      wire  = counterLow[2 LE] || ciphertext || tag[4]
 *                  RX: key = SK[ 0:16], prefix = SK[32:36],
 *                      wire  = counterLow[2 LE] || ciphertext || tag[4]
 *                  vendor: BleSecurityChipEncrypt (ze2) decrypt/encrypt using
 *                          SecurityChipUtil.AESDecrypt/AESEncrypt (u3p)
 *
 * The device keeps a 32-bit counter per direction; only the low 16 bits travel
 * on the wire and the high 16 bits are carried in the per-session counter state
 * ([S400StandardAuthSession]).
 */
object S400StandardAuth {

    /** Length of the derived session key in bytes. */
    const val SESSION_KEY_LENGTH = 64

    /** Length of each confirmation HMAC in bytes. */
    const val CONFIRMATION_LENGTH = 32

    /** AES-CCM authentication tag length on the wire, in bytes. */
    const val TAG_LENGTH_BYTES = 4

    /** AES-CCM nonce length in bytes. */
    const val NONCE_LENGTH = 12

    /** On-wire little-endian frame counter prefix length in bytes. */
    const val COUNTER_PREFIX_BYTES = 2

    private const val TAG_LENGTH_BITS = TAG_LENGTH_BYTES * 8
    private const val KEY_BYTES = 16

    /** HKDF `info` string used by the S400 login handshake (ASCII). */
    private val HKDF_INFO = "mible-login-info".toByteArray(Charsets.US_ASCII)

    /** Session-key offsets, matching the vendor key schedule. */
    const val RX_KEY_OFFSET = 0
    const val TX_KEY_OFFSET = 16
    const val RX_NONCE_PREFIX_OFFSET = 32
    const val TX_NONCE_PREFIX_OFFSET = 36

    /**
     * Auth characteristic (FE95, 0x0019) message opcodes as observed by the
     * vendor login connector (`BleStandardAuthLoginConnector`).
     */
    const val OPCODE_APP_CONFIRM = 10
    const val OPCODE_APP_RANDOM = 11
    const val OPCODE_DEV_CONFIRM = 12
    const val OPCODE_DEV_RANDOM = 13

    /**
     * Derive the 64-byte session key.
     *
     * HKDF-SHA256 with `IKM = token`, `salt = appRandom || devRandom` and
     * `info = "mible-login-info"`. Both randoms must be 16 bytes.
     *
     * @param token device login token (secret)
     * @param appRandom 16-byte random generated by the app
     * @param devRandom 16-byte random generated by the device
     */
    fun deriveSessionKey(token: ByteArray, appRandom: ByteArray, devRandom: ByteArray): ByteArray {
        require(token.isNotEmpty()) { "token must not be empty" }
        require(appRandom.size == 16) { "appRandom must be 16 bytes" }
        require(devRandom.size == 16) { "devRandom must be 16 bytes" }

        // HKDF-Extract: PRK = HMAC(salt, IKM)
        val salt = appRandom + devRandom
        val prk = hmacSha256(salt, token)

        // HKDF-Expand over "mible-login-info" to 64 bytes
        val okm = ByteArray(SESSION_KEY_LENGTH)
        var previous = ByteArray(0)
        var offset = 0
        var blockIndex = 1
        while (offset < SESSION_KEY_LENGTH) {
            val mac = newHmac(prk)
            mac.update(previous)
            mac.update(HKDF_INFO)
            mac.update(blockIndex.toByte())
            previous = mac.doFinal()
            val n = minOf(previous.size, SESSION_KEY_LENGTH - offset)
            System.arraycopy(previous, 0, okm, offset, n)
            offset += n
            blockIndex++
        }
        return okm
    }

    /**
     * Device confirmation: `HMAC-SHA256(SK[0:16], devRandom || appRandom)`.
     * The device proves knowledge of the session key with this value.
     */
    fun deviceConfirmation(sessionKey: ByteArray, appRandom: ByteArray, devRandom: ByteArray): ByteArray {
        requireSessionKey(sessionKey)
        return hmacSha256(sessionKey.copyOfRange(RX_KEY_OFFSET, RX_KEY_OFFSET + KEY_BYTES), devRandom + appRandom)
    }

    /**
     * App confirmation: `HMAC-SHA256(SK[16:32], appRandom || devRandom)`.
     * The app proves knowledge of the session key with this value.
     */
    fun appConfirmation(sessionKey: ByteArray, appRandom: ByteArray, devRandom: ByteArray): ByteArray {
        requireSessionKey(sessionKey)
        return hmacSha256(sessionKey.copyOfRange(TX_KEY_OFFSET, TX_KEY_OFFSET + KEY_BYTES), appRandom + devRandom)
    }

    /** Constant-time comparison of a received confirmation against the expected one. */
    fun confirmationsMatch(expected: ByteArray, received: ByteArray): Boolean {
        if (expected.size != received.size) return false
        return java.security.MessageDigest.isEqual(expected, received)
    }

    /**
     * Build the 12-byte AES-CCM nonce: `prefix[4] || 00 00 00 00 || LE32(counter)`.
     */
    fun buildNonce(prefix: ByteArray, counter: Int): ByteArray {
        require(prefix.size == 4) { "nonce prefix must be 4 bytes" }
        val nonce = ByteArray(NONCE_LENGTH)
        System.arraycopy(prefix, 0, nonce, 0, 4)
        // nonce[4..8] stays zero
        ByteBuffer.wrap(nonce, 8, 4).order(ByteOrder.LITTLE_ENDIAN).putInt(counter)
        return nonce
    }

    /**
     * Encrypt `plaintext` for transmission (app -> device).
     *
     * @return `LE16(counter) || ciphertext || tag[4]`
     */
    fun encryptFrame(sessionKey: ByteArray, plaintext: ByteArray, counter: Int): ByteArray {
        requireSessionKey(sessionKey)
        val key = sessionKey.copyOfRange(TX_KEY_OFFSET, TX_KEY_OFFSET + KEY_BYTES)
        val nonce = buildNonce(sessionKey.copyOfRange(TX_NONCE_PREFIX_OFFSET, TX_NONCE_PREFIX_OFFSET + 4), counter)
        val sealed = ccmEncrypt(key, nonce, plaintext)
        return counterPrefix(counter) + sealed
    }

    /**
     * Decrypt a frame received from the device (device -> app).
     *
     * @param rxCounterHigh high 16 bits of the receive counter (the low 16 bits
     *   are carried in the frame). Pass 0 for the first frames of a session.
     * @return the plaintext, or `null` if the frame is malformed or the
     *   authentication tag does not verify (tamper/counter/key mismatch).
     */
    fun decryptFrame(sessionKey: ByteArray, frame: ByteArray, rxCounterHigh: Int = 0): ByteArray? {
        requireSessionKey(sessionKey)
        if (frame.size < COUNTER_PREFIX_BYTES + TAG_LENGTH_BYTES) return null
        val low = (frame[0].toInt() and 0xFF) or ((frame[1].toInt() and 0xFF) shl 8)
        val counter = (rxCounterHigh shl 16) or low
        val key = sessionKey.copyOfRange(RX_KEY_OFFSET, RX_KEY_OFFSET + KEY_BYTES)
        val nonce = buildNonce(sessionKey.copyOfRange(RX_NONCE_PREFIX_OFFSET, RX_NONCE_PREFIX_OFFSET + 4), counter)
        return ccmDecrypt(key, nonce, frame.copyOfRange(COUNTER_PREFIX_BYTES, frame.size))
    }

    /** Build the 2-byte little-endian on-wire counter prefix. */
    fun counterPrefix(counter: Int): ByteArray =
        byteArrayOf((counter and 0xFF).toByte(), ((counter ushr 8) and 0xFF).toByte())

    // ---- internals -------------------------------------------------------

    private fun requireSessionKey(sessionKey: ByteArray) {
        require(sessionKey.size == SESSION_KEY_LENGTH) { "session key must be $SESSION_KEY_LENGTH bytes" }
    }

    private fun newHmac(key: ByteArray): Mac {
        val mac = Mac.getInstance("HmacSHA256")
        mac.init(SecretKeySpec(key, "HmacSHA256"))
        return mac
    }

    private fun hmacSha256(key: ByteArray, data: ByteArray): ByteArray =
        newHmac(key).doFinal(data)

    private fun ccmEncrypt(key: ByteArray, nonce: ByteArray, plaintext: ByteArray): ByteArray {
        val ccm = CCMBlockCipher.newInstance(AESEngine.newInstance())
        ccm.init(true, AEADParameters(KeyParameter(key), TAG_LENGTH_BITS, nonce, ByteArray(0)))
        val out = ByteArray(ccm.getOutputSize(plaintext.size))
        val len = ccm.processBytes(plaintext, 0, plaintext.size, out, 0)
        ccm.doFinal(out, len)
        return out
    }

    private fun ccmDecrypt(key: ByteArray, nonce: ByteArray, ciphertext: ByteArray): ByteArray? =
        try {
            val ccm = CCMBlockCipher.newInstance(AESEngine.newInstance())
            ccm.init(false, AEADParameters(KeyParameter(key), TAG_LENGTH_BITS, nonce, ByteArray(0)))
            val out = ByteArray(ccm.getOutputSize(ciphertext.size))
            val len = ccm.processBytes(ciphertext, 0, ciphertext.size, out, 0)
            ccm.doFinal(out, len)
            out
        } catch (e: Exception) {
            // InvalidCipherTextException (tag failure) or any malformed input.
            null
        }
}

/**
 * Stateful convenience wrapper that mirrors the vendor per-direction counter
 * (`BleSecurityChipEncrypt.EncryptCounter`). Only the session key is retained;
 * no secret is derived or stored by this class.
 */
class S400StandardAuthSession(private val sessionKey: ByteArray) {

    /** Full 32-bit counter used for the next outbound frame. */
    var appCounter: Int = 0
        private set

    /** Low 16 bits of the last received counter (device side). */
    var deviceCounterLow: Int = 0
        private set

    /** High 16 bits of the device counter, advanced on low-word wrap. */
    var deviceCounterHigh: Int = 0
        private set

    private var receivedAnyFrame = false

    private fun counterOf(low: Int, high: Int): Int = (high shl 16) or (low and 0xFFFF)

    /** Encrypt [plaintext] and advance [appCounter] (mirrors `addAppLowCounter`). */
    fun encrypt(plaintext: ByteArray): ByteArray {
        val low = appCounter and 0xFFFF
        val frame = S400StandardAuth.encryptFrame(sessionKey, plaintext, appCounter)
        val nextLow = (low + 1) and 0xFFFF
        val high = (appCounter ushr 16) and 0xFFFF
        // The vendor advances the high word at BOTH bit-15 transitions.
        val signChanged = ((low xor nextLow) and 0x8000) != 0
        appCounter = counterOf(nextLow, if (signChanged) (high + 1) and 0xFFFF else high)
        return frame
    }

    /** Authenticate before updating the receive counter; reject replays and stale frames. */
    fun decrypt(frame: ByteArray): ByteArray? {
        if (frame.size < S400StandardAuth.COUNTER_PREFIX_BYTES + S400StandardAuth.TAG_LENGTH_BYTES) return null
        val low = (frame[0].toInt() and 0xFF) or ((frame[1].toInt() and 0xFF) shl 8)
        // A forward delta under half the counter space avoids treating an old
        // packet as a wrap. The first packet has no prior counter to compare.
        if (receivedAnyFrame) {
            val delta = (low - deviceCounterLow) and 0xFFFF
            if (delta == 0 || delta > 0x7FFF) return null
        }
        val signChanged = receivedAnyFrame && ((deviceCounterLow xor low) and 0x8000) != 0
        val nextHigh = if (signChanged) (deviceCounterHigh + 1) and 0xFFFF else deviceCounterHigh
        val plaintext = S400StandardAuth.decryptFrame(sessionKey, frame, nextHigh) ?: return null
        deviceCounterLow = low
        deviceCounterHigh = nextHigh
        receivedAnyFrame = true
        return plaintext
    }
}
